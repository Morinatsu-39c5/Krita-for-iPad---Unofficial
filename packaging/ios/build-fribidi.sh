#!/usr/bin/env bash
source "$(dirname "$0")/common.sh"
archive="$PROJECT_ROOT/.deps/downloads/fribidi-1.0.16.tar.xz"
src="$PROJECT_ROOT/.deps/src/fribidi-1.0.16"
bld="$PROJECT_ROOT/.build/deps-ios/fribidi"
if [[ ! -f "$archive" ]]; then
 curl -fL --retry 2 https://github.com/fribidi/fribidi/releases/download/v1.0.16/fribidi-1.0.16.tar.xz -o "$archive"
fi
printf '%s  %s\n' 1b1cde5b235d40479e91be2f0e88a309e3214c8ab470ec8a2744d82a5a9ea05c "$archive" | shasum -a 256 -c -
if [[ ! -d "$src" ]]; then tar -xf "$archive" -C "$PROJECT_ROOT/.deps/src"; fi
export PATH="$PROJECT_ROOT/.venv/bin:$PATH"
# Generated by build-fontconfig.sh with the selected SDK and explicit iOS flags.
cross="$PROJECT_ROOT/.build/deps-ios/fontconfig/ios.ini"
[[ -f "$cross" ]] || { echo 'Build Fontconfig first to generate the cross file'; exit 1; }
meson setup "$bld" "$src" --cross-file "$cross" --prefix "$PROJECT_ROOT/.deps/ios" --libdir lib --default-library static --buildtype release --wrap-mode=nofallback -Ddocs=false -Dbin=false -Dtests=false 2>&1 | tee "$PROJECT_ROOT/logs/fribidi-configure.log"
meson compile -C "$bld" -j "${BUILD_JOBS:-4}" 2>&1 | tee "$PROJECT_ROOT/logs/fribidi-build.log"
meson install -C "$bld" 2>&1 | tee "$PROJECT_ROOT/logs/fribidi-install.log"
python3 "$IOS_SCRIPT_DIR/quote-pkgconfig-paths.py" "$PROJECT_ROOT/.deps/ios/lib/pkgconfig"
