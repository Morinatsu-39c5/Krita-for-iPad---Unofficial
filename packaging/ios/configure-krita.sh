#!/usr/bin/env bash
source "$(dirname "$0")/common.sh"
KRITA_SOURCE_DIR="${KRITA_SOURCE_DIR:-$PROJECT_ROOT/upstream/krita}"
KRITA_BUILD_DIR="${KRITA_BUILD_DIR:-$PROJECT_ROOT/.build/krita-ios}"
KRITA_DEPS_PREFIX="${KRITA_DEPS_PREFIX:-$PROJECT_ROOT/.deps/ios}"
cmake -S "$KRITA_SOURCE_DIR" -B "$KRITA_BUILD_DIR" -G "${KRITA_GENERATOR:-Ninja}" \
 -DCMAKE_TOOLCHAIN_FILE="$QT_IOS_PREFIX/lib/cmake/Qt6/qt.toolchain.cmake" \
 -DECM_DIR="$PROJECT_ROOT/.deps/host/share/ECM/cmake" -DQT_HOST_PATH="$QT_HOST_PATH" -DCMAKE_SYSTEM_NAME=iOS \
 -DCMAKE_OSX_SYSROOT=iphoneos -DCMAKE_OSX_ARCHITECTURES=arm64 \
 -DCMAKE_OSX_DEPLOYMENT_TARGET=17.0 -DCMAKE_BUILD_TYPE="${KRITA_BUILD_CONFIG:-Release}" \
 -DKRITA_IOS_BUNDLE_ID="${KRITA_IOS_BUNDLE_ID:-org.example.krita}" \
 -DKRITA_IOS_TEAM_ID="${KRITA_IOS_TEAM_ID:-}" \
 -DKF6_HOST_TOOLING="$PROJECT_ROOT/.deps/host/lib/cmake" \
 -DCMAKE_FIND_ROOT_PATH="$KRITA_DEPS_PREFIX" \
 -DCMAKE_PREFIX_PATH="$KRITA_DEPS_PREFIX;$QT_IOS_PREFIX;$PROJECT_ROOT/.deps/host" \
 -DBoost_INCLUDE_DIR="$PROJECT_ROOT/.deps/src/boost_1_87_0" -DBoost_NO_BOOST_CMAKE=ON \
 -DPNG_LIBRARY_RELEASE="$KRITA_DEPS_PREFIX/lib/libpng16.a" -DPNG_LIBRARY_DEBUG="$KRITA_DEPS_PREFIX/lib/libpng16.a" \
 -DBUILD_SHARED_LIBS=OFF -DBUILD_WITH_QT6=ON -DALLOW_UNSTABLE=QT6 -DBUILD_TESTING=OFF \
 -DCMAKE_INSTALL_PREFIX="$PROJECT_ROOT/.build/krita-ios-install" \
 "$@" 2>&1 | tee "$PROJECT_ROOT/logs/configure-krita-ios.log"
